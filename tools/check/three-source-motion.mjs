import assert from 'node:assert/strict';
import {sourceActorFoot,projectOriginalActor,headingForSourceD8,
sourceKnightMotion} from '../../experiments/three/source-motion.mjs';
const eq=(a,b)=>assert.ok(Math.abs(a-b)<1e-7,'expected '+a+' ≈ '+b);
const actor={x:104.25,y:320.5,moving:false,walk:0,run:0,jump:0,d8:0};
const CW=5.4,CH=8.28,pitch=.87,h=175;
const [sx,sy]=sourceActorFoot(actor,CW,CH);
eq(sx,actor.x*CW);eq(sy,(actor.y+.7)*CH);
const p=projectOriginalActor(actor,CW,CH,pitch,h);
eq(-p.position[0],sx);
eq(-p.position[1]*Math.cos(pitch)-p.position[2]*Math.sin(pitch),sy);
eq(p.scale*8.9*Math.cos(pitch),h);
eq(headingForSourceD8(0),Math.PI);
eq(headingForSourceD8(2),Math.PI/2);
eq(headingForSourceD8(4),0);
eq(headingForSourceD8(6),-Math.PI/2);
eq(headingForSourceD8(8),Math.PI);
const immutable=JSON.stringify(actor);
const idle=sourceKnightMotion(actor,null,.05,CW,CH);
assert.equal(idle.movement.speed,0);
assert.equal(idle.movement.jump,false);
const walk={...actor,y:actor.y-1,moving:true,walk:1,d8:4};
const moving=sourceKnightMotion(walk,idle.sample,.1,CW,CH);
assert.ok(moving.movement.speed>=8);
assert.equal(moving.movement.heading,0);
const jump={...walk,jump:1,run:1};
const first=sourceKnightMotion(jump,moving.sample,.1,CW,CH);
assert.equal(first.movement.jump,true);
assert.equal(first.movement.run,true);
assert.equal(sourceKnightMotion(jump,first.sample,.1,CW,CH).movement.jump,false);
assert.equal(JSON.stringify(actor),immutable);
assert.throws(()=>sourceActorFoot(null,CW,CH));
assert.throws(()=>projectOriginalActor(actor,CW,CH,pitch,-1));
console.log('PASS source player -> Three knight: projected glyph feet, 8 headings, real walk/run, one-shot jump and immutable author state');
