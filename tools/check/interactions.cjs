// Standalone contract tests for the shared interaction registry.
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.resolve(__dirname, '../../src/systems/interactions.js'), 'utf8');
const player = { x: 0, y: 0 };
const props = [], npcs = [];
const env = { player, props, npcs, CW: 5, CH: 10, say(e, message) { e.say = message; e.sayT = 3; } };
vm.createContext(env);
vm.runInContext(source + '\nthis.interactions = { registerInteractionAction, pickInteraction, performInteraction, interactionAvailable, INTERACTION_ACTIONS };', env);
const api = env.interactions;
const pass = name => console.log('PASS ' + name);
const reject = (name, fn, pattern) => { assert.throws(fn, pattern); pass(name); };
assert.equal(api.pickInteraction(), null); pass('no targets yields no prompt');
assert.equal(api.performInteraction(null), false); pass('missing target does nothing');
reject('invalid action kind', () => api.registerInteractionAction('bad type', () => {}), /Invalid action/);
reject('duplicate action kind', () => api.registerInteractionAction('talk', () => {}), /Duplicate/);
reject('invalid handler', () => api.registerInteractionAction('open', null), /Duplicate\/invalid/);
let used = 0;
const gate = { x: 5, y: 2, r: 14, label: 'push the great gate', action: 'inspect', need: () => false, onUse: () => used++ };
props.push({ spots: [gate] });
assert.equal(api.pickInteraction(), null); pass('gate condition filters action');
gate.need = () => true;
assert.equal(api.pickInteraction(), gate); pass('gate is available in range');
assert.equal(api.performInteraction(gate), true); assert.equal(used, 1); pass('inspect dispatch invokes callback once');
gate.x = 80;
assert.equal(api.pickInteraction(), null); assert.equal(api.performInteraction(gate), false); pass('gate out of range rejected, including stale pointer');
gate.x = 4;
const plain = { x: 3, y: 0, r: 5, label: 'legacy use', use: () => used++ };
props.push({ spots: [plain] });
assert.equal(api.pickInteraction(), plain); assert.equal(api.performInteraction(plain), true); pass('legacy use callback preserved');
const npc = { x: 1, y: 0, actorType: 'villager', actorId: 'npc-a', talkRadius: 5, name: 'Странник', lines: ['Первая', 'Вторая'], sayCd: 0, tx: 1, ty: 0 };
npcs.push(npc);
const talk = api.pickInteraction();
assert.equal(talk.action, 'talk'); assert.equal(talk.targetId, 'npc-a'); pass('nearest active NPC is a talk target');
assert.equal(api.performInteraction(talk), true); assert.equal(npc.say, 'Первая'); assert.equal(npc.dialogIndex, 1);
assert.equal(api.performInteraction(talk), true); assert.equal(npc.say, 'Вторая'); assert.equal(npc.dialogIndex, 2);
assert.equal(api.performInteraction(talk), true); assert.equal(npc.say, 'Первая'); pass('talk lines advance in order and wrap');
npc.x = 200;
assert.equal(api.performInteraction(talk), false); pass('stale NPC position is revalidated at dispatch');
npc.x = 1;
npcs.splice(0, 1);
assert.equal(api.performInteraction(talk), false); pass('despawned NPC cannot be used through stale prompt');
const silent = { x: 1, y: 0, actorType: 'villager', actorId: 'npc-b', talkRadius: 5, name: 'Silent', lines: [] };
npcs.push(silent);
assert.equal(api.pickInteraction(), plain); pass('NPC without lines has no talk prompt');
npcs.length = 0;
assert.equal(api.performInteraction({ x: 0, y: 0, r: 10, action: 'not-registered' }), false); pass('unregistered actions never execute');
api.registerInteractionAction('activate', spot => { used++; return spot.allowed; });
const custom = { x: 0, y: 0, r: 5, action: 'activate', allowed: true };
assert.equal(api.performInteraction(custom), true); pass('new action kind is registerable without editing game core');
custom.allowed = false;
assert.equal(api.performInteraction(custom), false); pass('custom action may decline without side effects to dispatch');
console.log('Interaction contracts passed.');
